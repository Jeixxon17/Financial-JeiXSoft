export interface Account {
  id: string
  name: string
  type: 'debit' | 'credit' | 'savings' | 'cash'
  balance: number
  color: string
  icon: string
  // Credit card specific
  creditLimit?: number
  usedCredit?: number
  cutoffDate?: number
  paymentDate?: number
  minimumPayment?: number
  totalToPay?: number
  // Interés mensual (%) de las compras a cuotas con intereses
  interestRate?: number
  // Pago mínimo real de cada extracto, por fecha de corte (YYYY-MM-DD)
  statementMinimums?: Record<string, number>
  // Deuda que el banco cobra por cuotas y no está en los movimientos
  deferredDebts?: DeferredDebt[]
  // Últimos 4 dígitos, para reconocer la cuenta en las notificaciones del banco
  lastDigits?: string
}

// Movimiento leído de una notificación del celular, esperando confirmación
// Lo sube el lector nativo del celular tal cual llega; se interpreta al mostrarlo
// (utils/bankNotifications.ts), así se mejora sin reinstalar la app
export interface PendingTransaction {
  id: string
  package: string
  bank?: 'bancolombia' | 'nu'
  title: string
  text: string
  // Momento en que llegó la notificación (ISO)
  receivedAt: string
}

export interface DeferredDebt {
  id: string
  description: string
  amount: number
  installments: number
  // Fecha desde la que se factura (como la fecha de una compra)
  date: string
}

